#!/usr/bin/env python3
"""Add apps to the home stack.

    scripts/stack.py new <name> --title "Situation" --description "World news on a map"
        Create ../<name> from stack/template: a Flask app with health check,
        tests, CI, Dockerfile, ready for /<name>/ behind nginx.

    scripts/stack.py publish <name> [--icon globe] [--private]
        Create github.com/<owner>/<name>, push ../<name>, add it to
        stack/apps.toml, render, then commit and push the dashboard. The Pi's
        deploy timer then clones the app, builds it, starts it and routes
        /<name>/ to it; the dashboard shows its tile.

    scripts/stack.py render [--check]
        Regenerate compose.apps.yml and nginx/conf.d/apps/*.locations from
        stack/apps.toml (--check: fail if they're out of date; CI runs this).

    scripts/stack.py repos [--registry FILE|-]
        Print "name:branch:service:container:owner/repo" per registered app
        (deploy.sh reads this, from the dashboard's latest commit on GitHub).

Only the standard library: it runs on the Mac and on the Pi.
"""
import argparse
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tomllib
import urllib.error
import urllib.request

DASHBOARD = pathlib.Path(__file__).resolve().parent.parent
STACK_DIR = DASHBOARD.parent                      # the repos sit side by side
REGISTRY = DASHBOARD / "stack" / "apps.toml"
TEMPLATE = DASHBOARD / "stack" / "template"
COMPOSE_OUT = DASHBOARD / "compose.apps.yml"
NGINX_OUT = DASHBOARD / "nginx" / "conf.d" / "apps"
NAME_RE = re.compile(r"^[a-z][a-z0-9-]{1,30}$")
RESERVED = {"dashboard", "library", "calendar", "music", "tapes", "mcp", "nginx", "home-nginx",
            "api", "auth", "login", "oauth", "static", "assets"}
PORT = 8000                                        # every stack app listens here in its own container


# ---------- registry ----------

def load_apps(text: str | None = None) -> list[dict]:
    if text is None:
        if not REGISTRY.exists():
            return []
        text = REGISTRY.read_text()
    apps = tomllib.loads(text).get("app", [])
    for app in apps:
        app.setdefault("branch", "main")
        app.setdefault("icon", "")
        app.setdefault("description", "")
        app.setdefault("env", {})
    return apps


def _toml_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)   # a JSON string is a valid TOML basic string


def add_to_registry(app: dict):
    apps = [a for a in load_apps() if a["name"] != app["name"]] + [app]
    lines = [
        "# Apps added with scripts/stack.py (the core apps are in docker-compose.yml).",
        "# Each becomes a compose service and an nginx route at /<name>/; run",
        "# `scripts/stack.py render` after editing by hand.",
        "",
    ]
    for a in apps:
        lines += ["[[app]]"] + [f"{k} = {_toml_str(a[k])}" for k in
                                ("name", "repo", "branch", "title", "description", "icon")]
        if a.get("env"):
            lines.append("env = { " + ", ".join(f"{k} = {_toml_str(v)}" for k, v in a["env"].items()) + " }")
        lines.append("")
    REGISTRY.write_text("\n".join(lines))


# ---------- rendering ----------

def compose_yaml(apps: list[dict]) -> str:
    out = ["# Generated by scripts/stack.py from stack/apps.toml. Don't edit by hand.", ""]
    if not apps:
        return "\n".join(out + ["services: {}", ""])
    out.append("services:")
    for a in apps:
        n = a["name"]
        env = {"APPLICATION_ROOT": f"/{n}", "AUTH_PROXY_HEADER": "X-Forwarded-User", **a["env"]}
        out += [
            f"  {n}:",
            f"    build: ../{n}",
            f"    image: {n}:dev",
            f"    container_name: {n}",
            "    restart: unless-stopped",
            "    environment:",
            *[f"      {k}: {json.dumps(str(v))}" for k, v in env.items()],
            "    volumes:",
            f"      - ../{n}/instance:/app/instance",
            "    expose:",
            f'      - "{PORT}"',
            "    labels:",
            '      homehub.enable: "true"',
            f"      homehub.name: {json.dumps(a['title'])}",
            f'      homehub.route: "/{n}/"',
            f"      homehub.icon: {json.dumps(a['icon'])}",
            f"      homehub.description: {json.dumps(a['description'])}",
            "    healthcheck:",
            f"      test: [\"CMD\", \"python\", \"-c\", \"import urllib.request; urllib.request.urlopen('http://127.0.0.1:{PORT}/healthz')\"]",
            "      interval: 30s",
            "      timeout: 5s",
            "      retries: 3",
            "      start_period: 20s",
            "",
        ]
    return "\n".join(out)


def nginx_locations(app: dict) -> str:
    n = app["name"]
    var = "$app_" + n.replace("-", "_")
    return f"""# Generated by scripts/stack.py from stack/apps.toml. Don't edit by hand.
# /{n}/ → the {n} container, signed in through the dashboard. The upstream is
# resolved per request, so nginx starts even before the app's first build.
location = /{n} {{
    return 301 /{n}/;
}}

location /{n}/ {{
    auth_request       /auth/verify;
    auth_request_set   $user $upstream_http_x_user;
    proxy_set_header   X-Forwarded-User $user;
    proxy_set_header   X-Forwarded-User-Original "";

    resolver           127.0.0.11 valid=30s ipv6=off;
    set                {var} http://{n}:{PORT};
    rewrite            ^/{n}/(.*)$ /$1 break;
    proxy_pass         {var};
    proxy_set_header   Host $host;
    proxy_set_header   X-Real-IP $remote_addr;
    proxy_set_header   X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header   X-Forwarded-Proto https;
    proxy_set_header   X-Forwarded-Host $host;
    proxy_set_header   X-Forwarded-Prefix /{n};
}}
"""


def render(check: bool = False) -> bool:
    """Write the generated files; with check, report whether they're current."""
    apps = load_apps()
    wanted = {COMPOSE_OUT: compose_yaml(apps)}
    for a in apps:
        wanted[NGINX_OUT / f"{a['name']}.locations"] = nginx_locations(a)
    stale = [p for p, text in wanted.items() if not p.exists() or p.read_text() != text]
    extra = [p for p in NGINX_OUT.glob("*.locations") if p not in wanted] if NGINX_OUT.exists() else []
    if check:
        for p in stale + extra:
            shown = p.relative_to(DASHBOARD) if p.is_relative_to(DASHBOARD) else p
            print(f"out of date: {shown}", file=sys.stderr)
        return not (stale or extra)
    NGINX_OUT.mkdir(parents=True, exist_ok=True)
    for p, text in wanted.items():
        p.write_text(text)
    for p in extra:
        p.unlink()
    return True


# ---------- new ----------

def cmd_new(args):
    name = args.name
    if not NAME_RE.match(name) or name in RESERVED:
        sys.exit(f"'{name}' can't be an app name: use lowercase letters, digits and dashes, not {sorted(RESERVED)}")
    dest = STACK_DIR / name
    if dest.exists():
        sys.exit(f"{dest} already exists")
    shutil.copytree(TEMPLATE, dest)
    (dest / "gitignore").rename(dest / ".gitignore")
    for path in dest.rglob("*"):
        if path.is_file() and path.suffix in {".py", ".html", ".toml", ".md", ".yml", ""}:
            text = path.read_text()
            text = (text.replace("__NAME__", name).replace("__TITLE__", args.title)
                    .replace("__DESCRIPTION__", args.description))
            path.write_text(text)
    run(["uv", "lock", "-q"], cwd=dest)
    run(["git", "init", "-q", "-b", "main"], cwd=dest)
    run(["git", "add", "-A"], cwd=dest)
    run(["git", "commit", "-qm", f"small/create {name} from the stack template"], cwd=dest)
    print(f"Created {dest}. Build it, then: scripts/stack.py publish {name}")


# ---------- publish ----------

def github_token() -> str:
    """The token git already pushes with (from the credential helper)."""
    out = subprocess.run(["git", "credential", "fill"], input="protocol=https\nhost=github.com\n\n",
                         capture_output=True, text=True, env={**os.environ, "GIT_TERMINAL_PROMPT": "0"})
    for line in out.stdout.splitlines():
        if line.startswith("password="):
            return line.split("=", 1)[1]
    sys.exit("No GitHub credential found. Push to GitHub once from this Mac (or run `gh auth login`).")


def github(method: str, path: str, token: str, body: dict | None = None) -> tuple[int, dict]:
    req = urllib.request.Request(f"https://api.github.com{path}", method=method,
                                 data=json.dumps(body).encode() if body else None,
                                 headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json",
                                          "User-Agent": "home-stack"})
    try:
        with urllib.request.urlopen(req, timeout=30) as res:
            return res.status, json.loads(res.read() or b"{}")
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read() or b"{}")


def run(cmd, cwd=None):
    subprocess.run(cmd, cwd=cwd, check=True)


def cmd_publish(args):
    name = args.name
    src = STACK_DIR / name
    if not (src / ".git").exists():
        sys.exit(f"No repo at {src}; create it with: scripts/stack.py new {name}")
    pyproject = tomllib.loads((src / "pyproject.toml").read_text()).get("project", {})
    title = args.title or pyproject.get("name", name).replace("-", " ").title()
    description = args.description or pyproject.get("description", "")

    token = github_token()
    status, me = github("GET", "/user", token)
    if status != 200:
        sys.exit("The stored GitHub credential didn't work.")
    owner = me["login"]
    status, repo = github("GET", f"/repos/{owner}/{name}", token)
    if status == 404:
        status, repo = github("POST", "/user/repos", token,
                              {"name": name, "description": description, "private": args.private})
        if status != 201:
            sys.exit(f"Couldn't create {owner}/{name}: {repo.get('message')}")
        print(f"Created github.com/{owner}/{name}")
    elif status != 200:
        sys.exit(f"Couldn't check {owner}/{name}: {repo.get('message')}")

    remotes = subprocess.run(["git", "remote"], cwd=src, capture_output=True, text=True).stdout.split()
    if "origin" not in remotes:
        run(["git", "remote", "add", "origin", f"https://github.com/{owner}/{name}.git"], cwd=src)
    branch = subprocess.run(["git", "branch", "--show-current"], cwd=src, capture_output=True, text=True).stdout.strip()
    run(["git", "push", "-q", "-u", "origin", branch], cwd=src)

    add_to_registry({"name": name, "repo": f"{owner}/{name}", "branch": branch, "title": title,
                     "description": description, "icon": args.icon,
                     "env": next((a["env"] for a in load_apps() if a["name"] == name), {})})
    render()
    run(["git", "add", "stack/apps.toml", "compose.apps.yml", "nginx/conf.d/apps"], cwd=DASHBOARD)
    run(["git", "commit", "-qm", f"small/add {name} to the stack"], cwd=DASHBOARD)
    run(["git", "push", "-q"], cwd=DASHBOARD)
    print(f"Done. Once CI passes on both repos, the Pi deploys it at /{name}/ (usually within 10 minutes).")
    if args.private:
        print("Note: the repo is private; the Pi needs DEPLOY_GITHUB_TOKEN and git credentials to clone it.")


def cmd_render(args):
    ok = render(check=args.check)
    if args.check and not ok:
        sys.exit("Generated files are out of date: run scripts/stack.py render")
    if not args.check:
        print("Rendered", len(load_apps()), "app(s).")


def cmd_repos(args):
    text = None
    if args.registry == "-":
        text = sys.stdin.read()
    elif args.registry:
        text = pathlib.Path(args.registry).read_text()
    for a in load_apps(text):
        print(f"{a['name']}:{a['branch']}:{a['name']}:{a['name']}:{a['repo']}")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    new = sub.add_parser("new", help="create an app from the template")
    new.add_argument("name")
    new.add_argument("--title", required=True)
    new.add_argument("--description", default="")
    new.set_defaults(func=cmd_new)
    pub = sub.add_parser("publish", help="create the GitHub repo, push, register, deploy")
    pub.add_argument("name")
    pub.add_argument("--title", default="")
    pub.add_argument("--description", default="")
    pub.add_argument("--icon", default="")
    pub.add_argument("--private", action="store_true")
    pub.set_defaults(func=cmd_publish)
    ren = sub.add_parser("render", help="regenerate compose and nginx files")
    ren.add_argument("--check", action="store_true")
    ren.set_defaults(func=cmd_render)
    rep = sub.add_parser("repos", help="list registered apps for deploy.sh")
    rep.add_argument("--registry", default="", help="a registry file, or - for stdin")
    rep.set_defaults(func=cmd_repos)
    args = p.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()

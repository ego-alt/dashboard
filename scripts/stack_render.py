#!/usr/bin/env python3
"""Turn the apps enabled in the Deploy tab into compose services and nginx
routes. Run by deploy.sh on the Pi; standard library only.

    stack_render.py apps                print name:branch:name:name:owner/repo per enabled app
    stack_render.py render              write generated/compose.apps.yml and generated/nginx/*.locations;
                                        prints "changed" when nginx needs a reload
    stack_render.py health <name>       print "<port> <path>" from the app's manifest

Enabled apps are files in $DEPLOY_STATE_DIR/apps/<name>.json, written by the
dashboard: {"name", "repo", "branch"}. Each app's homestack.toml is read from
its clone at <stack>/<name>.
"""
import json
import os
import pathlib
import sys

STACK_DIR = pathlib.Path(__file__).resolve().parent.parent.parent       # the repos sit side by side
sys.path.insert(0, str(STACK_DIR / "dashboard"))
from app.stack_manifest import ICON_MAX_BYTES, ManifestError, name_problem, parse  # noqa: E402

STATE_DIR = pathlib.Path(os.environ.get("DEPLOY_STATE_DIR", "/var/lib/home-stack-deploy"))
GENERATED = STATE_DIR / "generated"


def enabled_apps(state_dir: pathlib.Path = STATE_DIR) -> list[dict]:
    apps = []
    for path in sorted((state_dir / "apps").glob("*.json")):
        try:
            app = json.loads(path.read_text())
        except (OSError, ValueError):
            continue
        if app.get("name") and app.get("repo") and not name_problem(app["name"]):
            app.setdefault("branch", "main")
            apps.append(app)
    return apps


def manifest(name: str, stack_dir: pathlib.Path = STACK_DIR) -> dict | None:
    try:
        return parse((stack_dir / name / "homestack.toml").read_text())
    except (OSError, ManifestError):
        return None


def compose_yaml(apps: list[tuple[dict, dict]], stack_dir: pathlib.Path = STACK_DIR) -> str:
    lines = ["# Generated by dashboard/scripts/stack_render.py from the Deploy tab. Don't edit.", ""]
    if not apps:
        return "\n".join(lines + ["services: {}", ""])
    lines.append("services:")
    for app, m in apps:
        n = app["name"]
        env = {"APPLICATION_ROOT": f"/{n}", "AUTH_PROXY_HEADER": "X-Forwarded-User", **m["env"]}
        lines += [
            f"  {n}:",
            f"    build: {json.dumps(str(stack_dir / n))}",
            f"    image: {n}:dev",
            f"    container_name: {n}",
            "    restart: unless-stopped",
            "    environment:",
            *[f"      {k}: {json.dumps(v)}" for k, v in env.items()],
        ]
        if m["data"]:
            lines += ["    volumes:", f"      - {json.dumps(str(stack_dir / n / 'instance') + ':' + m['data'])}"]
        lines += [
            "    expose:",
            f'      - "{m["port"]}"',
            "    labels:",
            '      homehub.enable: "true"',
            f"      homehub.name: {json.dumps(m['title'])}",
            f'      homehub.route: "/{n}/"',
            f"      homehub.description: {json.dumps(m['description'])}",
            *([f"      homehub.accent: {json.dumps(m['accent'])}"] if m["accent"] else []),
            "",
        ]
    return "\n".join(lines)


def nginx_locations(name: str, m: dict) -> str:
    var = "$app_" + name.replace("-", "_")
    return f"""# Generated by dashboard/scripts/stack_render.py from the Deploy tab. Don't edit.
# /{name}/ → the {name} container, behind the dashboard's sign-in. The address is
# resolved per request, so nginx starts even before the app's first build.
location = /{name} {{
    return 301 /{name}/;
}}

location /{name}/ {{
    auth_request       /auth/verify;
    auth_request_set   $user $upstream_http_x_user;
    proxy_set_header   X-Forwarded-User $user;
    proxy_set_header   X-Forwarded-User-Original "";

    resolver           127.0.0.11 valid=30s ipv6=off;
    set                {var} http://{name}:{m["port"]};
    rewrite            ^/{name}/(.*)$ /$1 break;
    proxy_pass         {var};
    proxy_http_version 1.1;
    proxy_set_header   Upgrade $http_upgrade;
    proxy_set_header   Connection $connection_upgrade;
    proxy_set_header   Host $host;
    proxy_set_header   X-Real-IP $remote_addr;
    proxy_set_header   X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header   X-Forwarded-Proto https;
    proxy_set_header   X-Forwarded-Host $host;
    proxy_set_header   X-Forwarded-Prefix /{name};
}}
"""


def render(state_dir: pathlib.Path = STATE_DIR, stack_dir: pathlib.Path = STACK_DIR) -> bool:
    """Write the generated files. True when nginx's routes changed."""
    out = state_dir / "generated"
    (out / "nginx").mkdir(parents=True, exist_ok=True)
    ready = [(a, m) for a in enabled_apps(state_dir) if (m := manifest(a["name"], stack_dir))]
    wanted = {out / "nginx" / f"{a['name']}.locations": nginx_locations(a["name"], m) for a, m in ready}
    changed = False
    for path, text in wanted.items():
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            changed = True
    for path in (out / "nginx").glob("*.locations"):
        if path not in wanted:
            path.unlink()
            changed = True
    # Icons are copied out of the clones so the dashboard can serve them.
    (out / "icons").mkdir(exist_ok=True)
    icons = {}
    for a, m in ready:
        repo = (stack_dir / a["name"]).resolve()
        src = (repo / m["icon"]).resolve() if m["icon"] else None
        if src and src.is_relative_to(repo) and src.is_file() and src.stat().st_size <= ICON_MAX_BYTES:
            data = src.read_bytes()
            if b"<svg" in data:
                icons[out / "icons" / f"{a['name']}.svg"] = data
    for path, data in icons.items():
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
    for path in (out / "icons").glob("*.svg"):
        if path not in icons:
            path.unlink()
    compose = out / "compose.apps.yml"
    text = compose_yaml(ready, stack_dir)
    if not compose.exists() or compose.read_text() != text:
        compose.write_text(text)
    return changed


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else ""
    if cmd == "apps":
        for a in enabled_apps():
            print(f"{a['name']}:{a['branch']}:{a['name']}:{a['name']}:{a['repo']}")
    elif cmd == "render":
        print("changed" if render() else "unchanged")
    elif cmd == "health" and len(argv) > 2:
        m = manifest(argv[2])
        if not m:
            return 1
        print(m["port"], m["health"])
    else:
        print(__doc__, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
